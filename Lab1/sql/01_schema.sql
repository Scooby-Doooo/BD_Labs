\set ON_ERROR_STOP on
\encoding UTF8
BEGIN;

-- Користувачі та ролі
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL CHECK (email LIKE '%_@_%._%'),
    display_name varchar(120) NOT NULL CHECK (btrim(display_name) <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE CHECK (code IN ('client','freelancer','admin')),
    name varchar(80) NOT NULL
);
CREATE TABLE user_roles (
    user_id bigint NOT NULL REFERENCES users(id),
    role_id bigint NOT NULL REFERENCES roles(id),
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE freelancer_profiles (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    title varchar(160) NOT NULL,
    bio text NOT NULL DEFAULT '',
    hourly_rate numeric(14,2) NOT NULL CHECK (hourly_rate > 0)
);
CREATE TABLE client_profiles (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    company_name varchar(160),
    description text NOT NULL DEFAULT ''
);

-- Довідники
CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE skills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE freelancer_skills (
    freelancer_id bigint NOT NULL REFERENCES freelancer_profiles(user_id),
    skill_id bigint NOT NULL REFERENCES skills(id),
    PRIMARY KEY (freelancer_id, skill_id)
);

-- Проєкти (soft delete + аудит)
CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES client_profiles(user_id),
    category_id bigint NOT NULL REFERENCES categories(id),
    title varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL,
    budget numeric(14,2) NOT NULL CHECK (budget > 0),
    deadline date NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','open','in_progress','completed','cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES users(id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES users(id),
    search_vector tsvector GENERATED ALWAYS AS
      (to_tsvector('simple'::regconfig, coalesce(title,'') || ' ' || coalesce(description,''))) STORED,
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);
CREATE TABLE project_skills (
    project_id bigint NOT NULL REFERENCES projects(id),
    skill_id bigint NOT NULL REFERENCES skills(id),
    PRIMARY KEY (project_id, skill_id)
);

-- Заявки, контракти, етапи, оплати
CREATE TABLE proposals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id),
    freelancer_id bigint NOT NULL REFERENCES freelancer_profiles(user_id),
    cover_letter text NOT NULL,
    proposed_amount numeric(14,2) NOT NULL CHECK (proposed_amount > 0),
    estimated_days integer NOT NULL CHECK (estimated_days > 0),
    status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','withdrawn')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES users(id),
    UNIQUE (project_id, freelancer_id)
);
CREATE TABLE contracts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL UNIQUE REFERENCES projects(id),
    proposal_id bigint NOT NULL UNIQUE REFERENCES proposals(id),
    agreed_amount numeric(14,2) NOT NULL CHECK (agreed_amount > 0),
    status varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','completed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES users(id)
);
CREATE TABLE milestones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES contracts(id),
    title varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    due_date date NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','submitted','approved'))
);
CREATE TABLE submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id bigint NOT NULL REFERENCES milestones(id),
    description text NOT NULL CHECK (btrim(description) <> ''),
    result_url text,
    submitted_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id bigint NOT NULL REFERENCES milestones(id),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    external_reference varchar(120) NOT NULL UNIQUE CHECK (btrim(external_reference) <> ''),
    paid_at timestamptz NOT NULL DEFAULT now()
);

-- Відгуки, повідомлення, портфоліо
CREATE TABLE reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES contracts(id),
    author_id bigint NOT NULL REFERENCES users(id),
    rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (contract_id, author_id)
);
CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id bigint NOT NULL REFERENCES contracts(id),
    sender_id bigint NOT NULL REFERENCES users(id),
    recipient_id bigint NOT NULL REFERENCES users(id),
    body text NOT NULL CHECK (btrim(body) <> ''),
    sent_at timestamptz NOT NULL DEFAULT now(),
    CHECK (sender_id <> recipient_id)
);
CREATE TABLE portfolio_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    freelancer_id bigint NOT NULL REFERENCES freelancer_profiles(user_id),
    title varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL DEFAULT '',
    project_url text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint NOT NULL REFERENCES users(id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES users(id),
    CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);
COMMIT;
