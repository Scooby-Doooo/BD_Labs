-- Реляційний варіант каталогу проєктів. Назви таблиць і обмеження взяті з Лабораторної №1.
-- Вторинні індекси та зовнішні ключі створюються після завантаження (02_indexes.sql).
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL CHECK (email LIKE '%_@_%._%'),
    display_name varchar(120) NOT NULL CHECK (btrim(display_name) <> ''),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE client_profiles (
    user_id bigint PRIMARY KEY,
    company_name varchar(160)
);
CREATE TABLE freelancer_profiles (
    user_id bigint PRIMARY KEY,
    title varchar(160) NOT NULL,
    hourly_rate numeric(14,2) NOT NULL CHECK (hourly_rate > 0)
);
CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE skills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL,
    category_id bigint NOT NULL,
    title varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    description text NOT NULL,
    budget numeric(14,2) NOT NULL CHECK (budget > 0),
    deadline date NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('draft','open','in_progress','completed','cancelled')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    search_vector tsvector GENERATED ALWAYS AS
      (to_tsvector('simple'::regconfig, coalesce(title,'') || ' ' || coalesce(description,''))) STORED
);
CREATE TABLE project_skills (
    project_id bigint NOT NULL,
    skill_id bigint NOT NULL,
    PRIMARY KEY (project_id, skill_id)
);
-- Нова вимога: у кожної категорії свій набір характеристик. Реляційна форма для цього: EAV.
CREATE TABLE project_attributes (
    project_id bigint NOT NULL,
    key varchar(60) NOT NULL,
    value varchar(200) NOT NULL,
    PRIMARY KEY (project_id, key)
);
CREATE TABLE proposals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL,
    freelancer_id bigint NOT NULL,
    cover_letter text NOT NULL,
    proposed_amount numeric(14,2) NOT NULL CHECK (proposed_amount > 0),
    estimated_days integer NOT NULL CHECK (estimated_days > 0),
    status varchar(20) NOT NULL CHECK (status IN ('pending','accepted','rejected','withdrawn')),
    created_at timestamptz NOT NULL
);
